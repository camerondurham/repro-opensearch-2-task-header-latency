def snapshot_files(root, directory, expected, allow_cache=False):
    actual = inventory(root / directory)
    if allow_cache:
        caches = {str(PurePosixPath(n).parent / '__pycache__' /
                      (PurePosixPath(n).stem + '.cpython-311.pyc'))
                  for n in expected if n.endswith('.py')}
        actual -= caches
    need(actual == set(expected), 'Unexpected/missing ' + directory + ' inventory')
    for name, digest in expected.items():
        need(isinstance(digest, str) and re.fullmatch('[0-9a-f]{64}', digest), 'Invalid SHA256')
        need(sha(safe_file(root, directory + '/' + name)) == digest, 'Frozen file mismatch: ' + name)


def locked_distributions(path):
    return {re.sub(r'[-_.]+', '-', name.lower()): version for name, version in
            re.findall(r'^([A-Za-z0-9_.-]+)==([^\s\\;]+)', path.read_text(), re.MULTILINE)}


