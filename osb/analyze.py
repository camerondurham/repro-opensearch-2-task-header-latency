    need(order in (SMOKE_ORDER, PARALLEL_ORDER, LEGACY_PARALLEL_ORDER, CAMPAIGN_ORDER),
         'Unexpected order: require controls and four AB/BA/AB/BA pairs for a campaign')
    frozen = (root/'source-manifest.json').exists()
    legacy = not frozen and order in (SMOKE_ORDER, LEGACY_PARALLEL_ORDER)
    need(frozen or legacy, 'Campaign/boundary smoke requires source-manifest')
    need(order != LEGACY_PARALLEL_ORDER or legacy, 'Two-unit parallel smoke is legacy only')
    boundary = frozen and order == PARALLEL_ORDER and sha(root/'source-manifest.json') == BOUNDARY_SOURCE_SHA
    mode = 'smoke' if order == SMOKE_ORDER else 'campaign' if order == CAMPAIGN_ORDER else 'quick'
    evidence_format = ('legacy-' if legacy else '') + ('parallel-smoke' if mode == 'quick' else mode)
    if boundary:
        evidence_format = 'boundary-smoke-pre-build-inputs'
    build = load_json(safe_file(root, 'build.json'))
    changed = ['org/opensearch/action/search/TransportSearchScrollAction.class']
    need(build['source_commit'] == SOURCE_COMMIT and build['stock_image'] == STOCK_IMAGE and
         build.get('stock_image_id', STOCK_ID) == STOCK_ID and build['sole_intervention_entries'] == changed and set(build['variants']) == {'baseline', 'candidate'} and
         all(v['changed_entries_from_stock'] == changed and re.fullmatch('sha256:[0-9a-f]{64}', v['image_id'])
             for v in build['variants'].values()), 'Unexpected build intervention')
    need(build['variants']['baseline']['image_id'] != build['variants']['candidate']['image_id'],
         'Baseline and candidate images must differ')
    source = validate_snapshot(root, build, boundary) if frozen else None
    if legacy:
        need(not any((root/p).exists() for p in ('code', 'build-inputs', 'software.json')),
             'Legacy evidence must not retrofit frozen provenance')
    previous_end = None
    for name, variant, smoke, control in order:
        receipt = load_json(safe_file(root, name + '/receipt.json'))
        quick = mode == 'quick'
        docs, nodes = (128, 1) if smoke else (128 if legacy else 4800 if quick else 12000, 3)
        need(receipt['name'] == name and receipt['variant'] == variant and receipt['smoke'] is smoke and
             receipt['control'] is control and receipt.get('quick', False) is quick,
             'Receipt disagrees with order: ' + name)
        need(type(receipt['documents']) is int and receipt['documents'] == docs and type(receipt['nodes']) is int and receipt['nodes'] == nodes,
             'Incorrect documents/nodes: ' + name)
