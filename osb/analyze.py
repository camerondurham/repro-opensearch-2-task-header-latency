def need(ok, message):
    if not ok:
        raise ValueError(message)


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        need(key not in result, 'Duplicate JSON key: ' + key)
        result[key] = value
    return result


def load_json(path):
    return json.loads(path.read_text(), object_pairs_hook=unique_object)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def safe_file(root, name):
    need(isinstance(name, str) and name and '\\' not in name, 'Unsafe evidence path')
    path = PurePosixPath(name)
    need(not path.is_absolute() and '..' not in path.parts and str(path) == name and name != '.',
         'Unsafe evidence path: ' + name)
    current = root
    need(not current.is_symlink(), 'Symlink evidence root')
    for part in path.parts:
        current = current / part
        need(not current.is_symlink(), 'Symlink evidence path: ' + name)
    need(current.is_file(), 'Missing evidence file: ' + name)
    return current


def inventory(root):
    need(root.is_dir() and not root.is_symlink(), 'Missing/unsafe evidence directory')
    found = set()
    for path in root.rglob('*'):
        need(not path.is_symlink(), 'Symlink evidence path: ' + str(path))
        if path.is_file():
            found.add(path.relative_to(root).as_posix())
        else:
            need(path.is_dir(), 'Nonregular evidence path')
    return found


def rows(path):
    text = gzip.decompress(path.read_bytes()).decode() if path.suffix == '.gz' else path.read_text()
    return [json.loads(line, object_pairs_hook=unique_object) for line in text.splitlines()]


